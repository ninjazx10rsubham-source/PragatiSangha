-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Members Table (সদস্য ও চাঁদা তালিকা)
CREATE TABLE IF NOT EXISTS members (
  id TEXT PRIMARY KEY DEFAULT ('mem_' || replace(gen_random_uuid()::text, '-', '')),
  sl_no INT GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  phone TEXT DEFAULT '',
  address TEXT DEFAULT '',
  member_type TEXT NOT NULL DEFAULT 'সক্রিয় সদস্য',
  target_amount NUMERIC(10, 2) DEFAULT 0,
  collected_amount NUMERIC(10, 2) DEFAULT 0,
  status TEXT DEFAULT 'বাকি', -- 'বাকি', 'আংশিক জমা', 'জমা হয়েছে'
  last_payment_date DATE,
  notes TEXT DEFAULT '',
  visible BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Payments & Chanda Receipts (রসিদ ও পেমেন্ট হিস্ট্রি)
CREATE TABLE IF NOT EXISTS payments (
  id TEXT PRIMARY KEY DEFAULT ('pay_' || replace(gen_random_uuid()::text, '-', '')),
  receipt_no TEXT NOT NULL UNIQUE,
  member_id TEXT REFERENCES members(id) ON DELETE SET NULL,
  member_name TEXT NOT NULL,
  amount NUMERIC(10, 2) NOT NULL,
  payment_date DATE DEFAULT CURRENT_DATE,
  payment_mode TEXT DEFAULT 'নগদ', -- 'নগদ', 'UPI / অনলাইন', 'অন্যান্য'
  collected_by TEXT DEFAULT 'কোষাধ্যক্ষ',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Market Entries (বাজারের ফর্দ ও খরচ)
CREATE TABLE IF NOT EXISTS market_entries (
  id TEXT PRIMARY KEY DEFAULT ('mk_' || replace(gen_random_uuid()::text, '-', '')),
  category TEXT NOT NULL,
  shop_name TEXT DEFAULT '',
  item_name TEXT NOT NULL,
  quantity TEXT DEFAULT '',
  amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  entry_date DATE DEFAULT CURRENT_DATE,
  notes TEXT DEFAULT '',
  visible BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Expenses (পূজার অন্যান্য বিবিধ খরচ ও ভাউচার)
CREATE TABLE IF NOT EXISTS expenses (
  id TEXT PRIMARY KEY DEFAULT ('exp_' || replace(gen_random_uuid()::text, '-', '')),
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  expense_date DATE DEFAULT CURRENT_DATE,
  paid_by TEXT DEFAULT 'সম্পাদক',
  bill_no TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  visible BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Bhog & Prasad Coupons (ভোগ বিতরণ ট্র্যাকার)
CREATE TABLE IF NOT EXISTS bhog_coupons (
  id TEXT PRIMARY KEY DEFAULT ('bhog_' || replace(gen_random_uuid()::text, '-', '')),
  house_no TEXT NOT NULL,
  family_head TEXT NOT NULL,
  phone TEXT DEFAULT '',
  coupon_count INT NOT NULL DEFAULT 1,
  status TEXT DEFAULT 'বাকি', -- 'বাকি', 'দেওয়া হয়েছে'
  delivered_time TIMESTAMPTZ,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Sponsors & Advertisements (বিজ্ঞাপন ও স্পনসরশিপ ট্র্যাকার)
CREATE TABLE IF NOT EXISTS sponsors (
  id TEXT PRIMARY KEY DEFAULT ('sp_' || replace(gen_random_uuid()::text, '-', '')),
  sponsor_name TEXT NOT NULL,
  contact_person TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  banner_type TEXT DEFAULT 'গেট ব্যানার', -- 'গেট ব্যানার', 'প্যান্ডেল তোরণ', 'স্মরণিকা বিজ্ঞাপন', 'স্টেজ ব্যানার'
  promised_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  paid_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  status TEXT DEFAULT 'বাকি', -- 'বাকি', 'আংশিক জমা', 'পরিশোধিত'
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Club Settings & Totals (ক্লাব কনফিগারেশন)
CREATE TABLE IF NOT EXISTS settings (
  id TEXT PRIMARY KEY DEFAULT 'primary_settings',
  club_name TEXT DEFAULT 'প্রগতি সংঘ',
  event_name TEXT DEFAULT 'শ্রী শ্রী শ্যামা পূজা ২০২৬',
  other_income NUMERIC(10, 2) DEFAULT 0,
  admin_pin TEXT DEFAULT '1234',
  membership_types JSONB DEFAULT '[
    {"id": "m1", "name": "সক্রিয় সদস্য", "amount": 0},
    {"id": "m2", "name": "পাড়ার নাগরিক বৃন্দ", "amount": 0},
    {"id": "m3", "name": "বিশেষ সদস্য", "amount": 0},
    {"id": "m4", "name": "সহযোগী সদস্য", "amount": 0},
    {"id": "m5", "name": "ক্লাবের সদস্য", "amount": 0}
  ]'::jsonb,
  market_categories JSONB DEFAULT '[
    "পুজোর ফুল", "ফল", "সবজি", "মুদিখানা", "পুজোর সামগ্রী",
    "ভোগের সামগ্রী", "সাজসজ্জা", "আলো", "অন্যান্য", "জরুরি বাজার"
  ]'::jsonb,
  expense_categories JSONB DEFAULT '[
    "প্রতিমা", "প্যান্ডেল", "পুজো", "ভোগ", "সাজসজ্জা", "আলো", "সাউন্ড ও মাইক", "আপ্যায়ন", "অন্যান্য"
  ]'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Insert default settings row if not present
INSERT INTO settings (id, other_income)
VALUES ('primary_settings', 0)
ON CONFLICT (id) DO NOTHING;

-- 9. Row Level Security (RLS) - Set to public read/write with anon key for club members
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE market_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE bhog_coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE sponsors ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public all access on members" ON members FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on payments" ON payments FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on market_entries" ON market_entries FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on expenses" ON expenses FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on bhog_coupons" ON bhog_coupons FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on sponsors" ON sponsors FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on settings" ON settings FOR ALL USING (true) WITH CHECK (true);

-- Enable Realtime for all tables
